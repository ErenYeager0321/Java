package Practice;

public class P3 {
//   Implementing a Parameterized Print Method in Java
	public static void main(String[] args) {
		String message = "Rezero is Peak";
		printmessage(message);
		
	}
	
	public static void printmessage(String message) {
		String a = message;
		System.out.println(a);
	}
	
}
