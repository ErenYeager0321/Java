package SuffixFloatAndLong;

public class SuffixFloatAndLong {
     public static void main(String[] args) {
//    	 • 'L' or 'l': Suffix for long literals. It tells Java, "Hey, this number is a long type!"
//    	 • 'F' or 'f': Suffix for float literals. It lets Java know, "This is a float, not a double!"	
    	 
//    	 float a = 3.147;Without "F" it will say Error "cannot convert from double to float "
//    	 long b = 2147483648;//Without "L" it will sAy int Range Exceed
      
    	  	float a = 3.147F;//Small Or big both can Be used
    	  	long b = 2147483648L;
    	  	System.out.println(a+"  "+b);
  
	}
}
