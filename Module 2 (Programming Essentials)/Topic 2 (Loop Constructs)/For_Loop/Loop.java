package For_Loop;

public class Loop {
	public static void main(String[] args) {
		//      Intialization ; Condition ; Incrementation
		for (int i=1;i<=5;i++) {
			System.out.println("Fuck Off Cunt ");//First this will print
			System.out.println("Fuck Off ");//Then This , then will repeat 
		}
		
		for (int i=5;i>=1;i--) {
			System.out.println(i + " Fuck Off Cunt");
		}
		
		for (int i=-5;i<=0;i++) {
			System.out.println(i + " Not Fuck");
		}
		
		for (int i=-1;i>=-5;i--) {
			System.out.println(i + " Fuck");
		}
	}
}
