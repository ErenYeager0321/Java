
public class OperatorsComparison {
  public static void main(String[] args) {
//	Comparison/Relational Operators
	  System.out.println();
	  System.out.println("20 > 10 ? "+(20>10));
	  System.out.println("20 < 10 ? "+(20<10));
	  System.out.println("20 >= 10 ? "+(20>=10));
	  System.out.println("20 >= 20 ? "+(20>=20));
	  System.out.println("20 <= 10 ? "+(20<=10));
	  System.out.println("20 <= 20 ? "+(20<=20));
	  System.out.println("20 == 10 ? "+(20==10));
	  System.out.println("20 == 20 ? "+(20==20));
	  System.out.println("20 != 10 ? "+(20!=10));
	  System.out.println("20 != 20 ? "+(20!=20));
	  
	  
	  
	  
  }
}
