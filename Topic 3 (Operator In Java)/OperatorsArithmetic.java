
public class OperatorsArithmetic {
      public static void main(String[] args) {
    	  System.out.println("Arithmetic Operators");
    	  int x = 10;
    	  int y = 3;
    	  System.out.println("Addition: " + (x + y)); // Output: 13
    	  System.out.println("Substraction: " + (x - y)); // Output: 7
    	  System.out.println("Multiplicaton: " + (x*y)); // Output : 30
    	  System.out.println("Division: " + (x / y)); // Output: 3
    	  System.out.println("Modulus: " + (x % y));  // Output: 1 (remainder)
	
    	  
    	  
      
    	  
      
      
      }
}
